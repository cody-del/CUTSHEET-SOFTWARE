import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {posix} from 'node:path';
const files=new Set(['/shop.html','/shop.js','/styles.css','/shop.css','/workspace.css','/assets/5-day-logo.png','/assets/frame-sky.png']);
for(const file of files){
 if(!file.endsWith('.js'))continue;
 const code=await readFile(new URL('../public'+file,import.meta.url),'utf8');
 for(const m of code.matchAll(/(?:from\s*|import\s*)['"](\.\/[^'"]+\.js)['"]/g))files.add(posix.join(posix.dirname(file),m[1]));
}
const assets=[...files].sort(),hash=createHash('sha256');
hash.update(await readFile(new URL('../public/shop-service-worker.js',import.meta.url)));
for(const file of assets)hash.update(file).update(await readFile(new URL('../public'+file,import.meta.url)));
await writeFile(new URL('../public/shop-offline-assets.js',import.meta.url),`// Generated by scripts/build-shop-offline.mjs; contains static assets only.\nself.SHOP_ASSETS=${JSON.stringify(assets)};\nself.SHOP_CACHE='cutsheet-shop-${hash.digest('hex').slice(0,16)}';\n`);
